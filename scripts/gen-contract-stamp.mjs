#!/usr/bin/env node
// Emit a generated "contract stamp" next to the generated API types.
//
// THE GAP THIS CLOSES (systems audit R9, still open until 2026-08-01):
// each consumer's CI drift gate regenerates api.gen.ts from its OWN vendored
// openapi/v1.yaml and diffs the result. That proves "my types match my copy" —
// it can never prove "my copy matches urafro-next". Worse, openapi-typescript
// does not emit `info.version` anywhere, so an upstream release that only bumps
// the version, or that changes prose/constraints without changing a TS type,
// produces NO diff at all. The 2026-07 audit found both consumers running
// hand-refreshed "1.2.0" hybrids of a 1.8.0 upstream for exactly this reason.
//
// The stamp makes the vendored copy's identity a tracked artifact: version plus
// a sha256 of the exact bytes. Now ANY upstream change shows up as a diff in the
// consumer's repo the moment it re-vendors, and `check-contract-sync.sh` can
// compare hashes instead of eyeballing.
//
// Usage: node scripts/gen-contract-stamp.mjs <spec.yaml> <out.ts>
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [, , specPath, outPath] = process.argv;
if (!specPath || !outPath) {
  console.error('usage: gen-contract-stamp.mjs <spec.yaml> <out.ts>');
  process.exit(2);
}

const raw = readFileSync(specPath);
const text = raw.toString('utf8');

// `info.version` without a YAML dependency: the first 2-space-indented
// `version:` inside the top-level `info:` block.
const infoIdx = text.split('\n').findIndex((l) => l.trimEnd() === 'info:');
if (infoIdx === -1) throw new Error(`no top-level 'info:' block in ${specPath}`);
let version = null;
for (const line of text.split('\n').slice(infoIdx + 1)) {
  if (/^\S/.test(line)) break; // left the info block
  const m = line.match(/^\s{2}version:\s*["']?([^"'\s]+)["']?\s*$/);
  if (m) {
    version = m[1];
    break;
  }
}
if (!version) throw new Error(`no info.version found in ${specPath}`);

const sha256 = createHash('sha256').update(raw).digest('hex');

writeFileSync(
  outPath,
  `// GENERATED by scripts/gen-contract-stamp.mjs — DO NOT EDIT.
//
// Identity of the vendored urafro-next /v1 contract this client was built from.
// Regenerated by the same npm script that regenerates the API types, so the
// existing CI drift gate (regen + \`git diff --exit-code\`) also covers it.
//
// If this file changes, the contract changed. If it did NOT change after a
// re-vendor, the vendored copy is byte-identical to what it was before.
export const CONTRACT_VERSION = '${version}';
export const CONTRACT_SHA256 = '${sha256}';
`,
);

console.log(`contract stamp → ${outPath}  (v${version}, sha256 ${sha256.slice(0, 12)}…)`);
